const fs = require('fs');
const path = require('path');
const solc = require('solc');

const contractPath = path.resolve(__dirname, '../contracts/ReviveProbe.sol');
const source = fs.readFileSync(contractPath, 'utf8');

const input = {
  language: 'Solidity',
  sources: {
    'ReviveProbe.sol': {
      content: source,
    },
  },
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode'],
      },
    },
  },
};

console.log('Compiling ReviveProbe.sol...');
const output = JSON.parse(solc.compile(JSON.stringify(input)));

if (output.errors) {
  let hasError = false;
  output.errors.forEach((err) => {
    console.log(err.formattedMessage);
    if (err.severity === 'error') hasError = true;
  });
  if (hasError) {
    process.exit(1);
  }
}

const contract = output.contracts['ReviveProbe.sol']['ReviveProbe'];
const abi = contract.abi;
const bytecode = contract.evm.bytecode.object;

const outDir = path.resolve(__dirname, '../src/contracts');
fs.mkdirSync(outDir, { recursive: true });

fs.writeFileSync(
  path.join(outDir, 'ReviveProbe.json'),
  JSON.stringify({ abi, bytecode: '0x' + bytecode }, null, 2)
);

const tsExport = `// Autogenerated by scripts/compile.js
export const REVIVE_PROBE_ABI = ${JSON.stringify(abi, null, 2)} as const;
export const REVIVE_PROBE_BYTECODE = "0x${bytecode}" as const;
export const DEFAULT_PROBE_ADDRESS = "0x7a39F90aE852D6cfEb24a9a46C0A9A30f78d6b9C";
`;

fs.writeFileSync(path.join(outDir, 'ReviveProbeABI.ts'), tsExport);
console.log('Successfully compiled ReviveProbe.sol and saved ABI + Bytecode.');
